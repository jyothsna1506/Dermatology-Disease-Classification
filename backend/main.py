"""
Production FastAPI application for Dermatology Disease Classification.
Wraps the pre-trained Gaussian Naive Bayes model with rigorous validation,
CORS support, medical metadata, and prediction probabilities.
"""

import json
import logging
import os
from typing import Any, Dict, List
import joblib
import numpy as np
from fastapi import FastAPI, HTTPException, Request, status
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import JSONResponse, FileResponse

from schemas import (
    ClassProbability,
    DermatologyInputFeatures,
    HealthResponse,
    PredictionResponse,
)

# Configure logging
logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")
logger = logging.getLogger("dermatology_api")



from contextlib import asynccontextmanager

# Global model state
MODEL = None
METADATA = None

MODEL_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "model"))
MODEL_FILE = os.path.join(MODEL_DIR, "gaussian_nb.joblib")
METADATA_FILE = os.path.join(MODEL_DIR, "metadata.json")

DISCLAIMER_TEXT = (
    "Medical Disclaimer: This prediction is generated by a Machine Learning model (Gaussian Naive Bayes) "
    "for educational and clinical research assistance only. It does NOT constitute medical diagnosis or "
    "clinical advice. Always consult a qualified dermatologist or physician for clinical evaluation."
)

def init_resources():
    global MODEL, METADATA
    if MODEL is not None and METADATA is not None:
        return

    logger.info("Initializing Dermatology Disease Classification Service...")

    if not os.path.exists(MODEL_FILE):
        logger.error(f"Model file not found at {MODEL_FILE}. Please run model/train.py first.")
        raise RuntimeError(f"Model file not found: {MODEL_FILE}")

    if not os.path.exists(METADATA_FILE):
        logger.error(f"Metadata file not found at {METADATA_FILE}.")
        raise RuntimeError(f"Metadata file not found: {METADATA_FILE}")

    try:
        MODEL = joblib.load(MODEL_FILE)
        logger.info(f"Loaded trained Gaussian Naive Bayes model from {MODEL_FILE}")
    except Exception as e:
        logger.error(f"Failed to load model: {e}")
        raise RuntimeError(f"Failed to load model: {e}")

    try:
        with open(METADATA_FILE, "r", encoding="utf-8") as f:
            METADATA = json.load(f)
        logger.info("Loaded dataset and feature metadata successfully.")
    except Exception as e:
        logger.error(f"Failed to load metadata: {e}")
        raise RuntimeError(f"Failed to load metadata: {e}")

@asynccontextmanager
async def lifespan(app: FastAPI):
    init_resources()
    yield

app = FastAPI(
    title="Dermatology Disease Classification API",
    description="Machine Learning service for erythemato-squamous dermatology disease classification.",
    version="1.0.0",
    lifespan=lifespan
)

# CORS setup
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],  # Permissive for development and testing
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

# Also ensure immediate initialization if imported directly
try:
    init_resources()
except Exception as e:
    logger.warning(f"Immediate resource initialization deferred to lifespan: {e}")

